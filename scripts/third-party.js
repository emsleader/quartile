// Writes THIRD_PARTY_LICENSES.md from the installed production dependencies (name, version, licence, licence
// text), or with --check fails when a bundled package has a licence outside the allowed list.
// Allowed: MIT, ISC, BSD-2-Clause, BSD-3-Clause, Apache-2.0, 0BSD, CC0-1.0, BlueOak-1.0.0, Unlicense.
// Packages without a machine-readable licence field are listed in EXCEPTIONS with the licence read by hand.
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const OKL = "MIT|ISC|BSD-2-Clause|BSD-3-Clause|Apache-2\\.0|0BSD|CC0-1\\.0|BlueOak-1\\.0\\.0|Unlicense|Zlib";
// a plain allowed licence, "A AND B" with both allowed, or "A OR B" with at least one allowed (we take that one)
const allowedLic = l => { const t = String(l).replace(/[()]/g, "").trim(); if (!t) return false; const one = x => new RegExp("^(" + OKL + ")$").test(x.trim());
  if (/\sOR\s/.test(t)) return t.split(/\s+OR\s+/).some(x => x.split(/\s+AND\s+/).every(one)); return t.split(/\s+AND\s+/).every(one); };
const EXCEPTIONS = {
  buffers: "MIT/X11 (stated in the package README; no licence field). Dependency of exceljs via unzipper.",
  chainsaw: "MIT/X11 (licence field). Dependency of exceljs via unzipper/binary.",
  mkdirp: "MIT (LICENSE file; old version without a licence field). Dependency of exceljs via unzipper.",
  rimraf: "ISC (LICENSE file; old version without a licence field). Dependency of exceljs via unzipper.",
  duck: "BSD-2-Clause (licence field says 'BSD'; LICENSE file is the 2-clause text). Dependency of mammoth via lop.",
};
const tree = JSON.parse(execFileSync("npm", ["ls", "--omit=dev", "--all", "--json", "--long"], { cwd: ROOT, encoding: "utf8", maxBuffer: 64 << 20 }));
const pkgs = new Map();
(function walk(deps) { for (const [name, d] of Object.entries(deps || {})) { if (!d.version || !d.path || d.missing) continue; if (!pkgs.has(name + "@" + d.version)) pkgs.set(name + "@" + d.version, { name, version: d.version, dir: d.path }); walk(d.dependencies); } })(tree.dependencies);
const rows = [], bad = [];
for (const p of [...pkgs.values()].sort((a, b) => a.name.localeCompare(b.name))) {
  const dir = p.dir && fs.existsSync(path.join(p.dir, "package.json")) ? p.dir : findDir(p.name); const j = dir ? JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8")) : {};
  let lic = j.license || (j.licenses || []).map(x => x.type || x).join(" OR ") || ""; if (typeof lic === "object") lic = lic.type;
  const ok = allowedLic(lic) || EXCEPTIONS[p.name];
  if (!ok) bad.push(`${p.name}@${p.version}: ${lic || "no licence field"}`);
  const lf = dir && fs.readdirSync(dir).find(f => /^(licen[cs]e|copying)(\.|$)/i.test(f));
  rows.push({ name: p.name, version: p.version, lic: lic || EXCEPTIONS[p.name] || "unknown", note: EXCEPTIONS[p.name], text: lf ? fs.readFileSync(path.join(dir, lf), "utf8").trim() : null });
}
function findDir(name) { const d = path.join(ROOT, "node_modules", name); return fs.existsSync(path.join(d, "package.json")) ? d : null; }
if (process.argv.includes("--check")) {
  if (bad.length) { console.error("Licences outside the allowed list:\n" + bad.join("\n")); process.exit(1); }
  console.log(`Licences: ${rows.length} bundled packages, all allowed.`); process.exit(0);
}
const md = ["# Third-party licences", "", "Generated by `node scripts/third-party.js` from the production dependencies in `package-lock.json`.",
  "Only MIT, ISC, BSD, Apache-2.0 and equally permissive licences are bundled. No GPL, AGPL or CPAL code is bundled.",
  "Word lists from proselint (BSD-3-Clause) and other projects used as data are credited in `data/THIRD-PARTY.md`.", "",
  "| Package | Version | Licence |", "|---|---|---|", ...rows.map(r => `| ${r.name} | ${r.version} | ${r.lic}${r.note ? " (see note)" : ""} |`), "", "## Notes", "",
  ...Object.entries(EXCEPTIONS).map(([k, v]) => `- ${k}: ${v}`), "", "## Licence texts", "",
  ...rows.filter(r => r.text).flatMap(r => [`### ${r.name} ${r.version}`, "", "```", r.text, "```", ""])];
fs.writeFileSync(path.join(ROOT, "THIRD_PARTY_LICENSES.md"), md.join("\n"));
console.log(`THIRD_PARTY_LICENSES.md: ${rows.length} packages.`);
