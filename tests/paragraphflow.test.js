"use strict";
const assert=require("node:assert/strict");
const P=require("../core/paragraphflow.js");
const intro="The Hungarian survey covered 656 establishments in 2019. Those establishments were assessed for fixed-asset purchases.\n\nThe survey also followed establishments into 2023. Their responses allow a matched comparison.";
const a=P.analyse({sectionText:intro,sectionRole:"introduction",previousSectionLast:"Previous research describes sample selection in enterprise surveys.",nextSectionFirst:"The methods define the survey samples and weights."});
assert.equal(a.paragraphCount,2);
assert.equal(a.paragraphs[0].metrics.sentences,2);
assert.equal(a.paragraphs[1].metrics.sentences,2);
assert.ok(a.paragraphs[0].metrics.medianSentenceWords>0);
assert.equal(P.paragraphMetrics("A 15.5-point gap was reported. The interval was 5.8 to 24.1 points.").sentences,2);
assert.equal(P.linkAssessment("Establishments were surveyed.", "Establishments were sampled.").status,"lexical_link_present");
assert.equal(P.linkAssessment("Energy costs rose.", "Sampling changed.").status,"manual_semantic_check");
const b=P.nextParagraphBrief({sectionRole:"introduction",lockedParagraphs:P.paragraphList(intro),nextParagraphPurpose:"Explain the survey estimands",verifiedEvidence:["Cross-sectional sample N=656 in 2019"],nextSectionGoal:"Introduce methods",protectedTerms:["sample-turnover"]});
assert.equal(b.stage,"ONE_PARAGRAPH_ONLY");
assert.equal(b.paragraphNumber,3);
assert.equal(b.lockedParagraphCount,2);
assert.equal(b.confirmedEvidenceAvailable.length,1);
assert.ok(b.instructions.some(x=>x.includes("exactly one paragraph")));
assert.throws(()=>P.nextParagraphBrief({verifiedEvidence:[3]}));
console.log("paragraphflow: all tests passed");
