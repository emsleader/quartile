"use strict";
const assert = require("node:assert/strict");
const F = require("../core/fermodels.js");
const rep = require("./fixture-fer-aggregates.json");
assert.equal(F.FORMULAE.length,12,"Twelve specified estimands/tests");
assert.equal(F.exactMcNemar(60,45).toFixed(9),"0.171564697");
assert.equal(F.exactMcNemar(0,0),1);
const a=F.audit(rep);
assert.equal(a.pass,true,JSON.stringify(a.checks.filter(x=>x.status==="fail")));
assert.equal(a.summary.failed,0);
assert.ok(a.notValidated.some(x=>x.includes("R scripts")),"R is not falsely certified");
const alter=structuredClone(rep);alter.point_estimates.net_sample_turnover_pp+=1;
assert.equal(F.audit(alter).pass,false,"Bad decomposition must fail");
assert.equal(F.audit(alter).checks.find(x=>x.id==="DECOMPOSITION_IDENTITY").status,"fail");
const tamper=structuredClone(rep);tamper.regression_diagnostics.logit_purchase_OR*=1.5;
assert.equal(F.audit(tamper).pass,false,"Incorrect odds ratio blocked");
const ci=structuredClone(rep);ci.independent_bootstrap_CI95.B5000.IPW_change_pp=[5,-3];
assert.equal(F.audit(ci).checks.find(x=>x.id==="CI_B5000_IPW_change_pp").status,"fail");
const ca=structuredClone(rep);ca.point_estimates.matched_change_pp=-7;
assert.equal(F.audit(ca).pass,false,"Paired change is not freely editable");
