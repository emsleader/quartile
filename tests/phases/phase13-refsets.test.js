// Curated reference sets (reference_set).
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
const home = fs.mkdtempSync(path.join(os.tmpdir(), "qrefset-")); process.env.QUARTILE_HOME = home;
const tool = (await import("../../tools/reference_set.js")).default;
const { getSet } = await import("../../core/library/refsets.js");
const s = getSet("alavi-core-2026");
assert.equal(s.items.length, 100); assert.equal(s.count, 100);
assert.equal(new Set(s.items.map(i => i.doi.toLowerCase())).size, 100, "DOIs unique");
assert.equal(new Set(s.items.map(i => i.key)).size, 100, "keys unique");
assert.ok(s.items.every(i => i.quartile === "Q1" && i.authors.length && i.year && i.journal && /^10\./.test(i.doi)));
assert.ok(!s.items.some(i => /^10\.(3386|2139)\//.test(i.doi)), "journal versions, not working papers");
assert.equal(s.curator.orcid, "0009-0003-8430-211X");
assert.match(s.note, /not their author/);
assert.equal(Object.values(s.topics).reduce((a, b) => a + b, 0), 100);
const bib = fs.readFileSync(new URL("../../data/reference-sets/alavi-core-2026.bib", import.meta.url), "utf8");
assert.equal((bib.match(/@article\{/g) || []).length, 100);
const list = await tool.handler({ action: "list" });
assert.ok(list.sets.some(x => x.id === "alavi-core-2026"));
const show = await tool.handler({ action: "show", set: "alavi-core-2026", topic: "leasing" });
assert.equal(show.count, s.topics.leasing);
await assert.rejects(() => tool.handler({ action: "show", set: "../x" }));
const a = await tool.handler({ action: "load", set: "alavi-core-2026" });
assert.equal(a.added, 100); assert.match(a.collection, /curated by Seyed Mehdi Alavi/);
assert.equal(a.items[0].quartile, "Q1");
const b = await tool.handler({ action: "load", set: "alavi-core-2026" });
assert.equal(b.added, 0); assert.equal(b.duplicates, 100);
console.log("phase13 reference sets: ok");
