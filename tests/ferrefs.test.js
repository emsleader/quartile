"use strict";
const assert=require("node:assert/strict");
const R=require("../core/ferrefs.js");
const s=R.status();
assert.equal(s.count,100);
assert.equal(s.doi_verified,100);
assert.equal(s.year_discrepancies,11);
assert.equal(s.priority_A,19);
assert.equal(s.not_primary_empirical,2);
assert.equal(s.latest_q1_verified,0);
assert.equal(s.fulltext_checked_within_this_corpus,0);
assert.equal(s.previously_read_in_separate_audit,3);
let r=R.search({query:"SME access to finance",limit:100});
assert.ok(r.count>0 && r.records.length>0);
assert.ok(r.records.every(x=>x.doi_url.startsWith("https://doi.org/")));
assert.equal(R.search({query:"FERQ1-047"}).records[0].research_type,"commentary");
assert.equal(R.search({query:"FERQ1-066"}).records[0].research_type,"IMF publication (not peer-reviewed journal article)");
assert.ok(R.search({priority:"A_method_direct",limit:100}).records.length===19);
assert.ok(R.search({query:"not-a-real-existing-record"}).count===0);
assert.throws(()=>R.search({limit:101}));
console.log("FER reference library: 100/100 screened, 11 year discrepancies, 19 priority A, 2 not-primary papers; no false fulltext/Q1 claims.");
